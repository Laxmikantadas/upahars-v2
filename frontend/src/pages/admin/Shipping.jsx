import { useState } from 'react';
import { api, ApiError } from '../../lib/api';
import { fmtDateTime, formatCountdown, isPincode, STATE_STYLE, useShippingToken } from '../../lib/shipping';
import { Empty, PageHeader } from './ui';
import { notify } from '../../lib/notify';
const errText = (e) => { const m = e instanceof ApiError ? e.message : 'Something went wrong. Please try again.'; notify.error(m); return m; };
function StatusCard({ s, onForget }) {
    const style = STATE_STYLE[s.state];
    if (s.loading)
        return <Empty>Loading courier token…</Empty>;
    return (<section className="card space-y-3" aria-labelledby="st-h">
      <div className="flex flex-wrap items-center gap-3">
        <h2 id="st-h" className="text-xl font-bold">Courier token (Shipex)</h2>
        <span className={`rounded-full px-2.5 py-0.5 text-xs font-bold ${style.chip}`}>{style.label}</span>
      </div>

      {!s.configured ? (<p className="text-sm text-neutral-700">No token is saved yet. Generate one below. Until then, pincode checks cannot run and customers are told “we could not confirm delivery”, but orders still go through.</p>) : (<>
          <div>
            <p className="text-sm text-neutral-600">{s.state === 'expired' ? 'This token has expired. Generate a new one below.' : 'Time left before the token expires'}</p>
            <p className={`mt-1 font-mono text-3xl font-bold tabular-nums ${s.state === 'expired' ? 'text-red-700' : s.state === 'expiring' ? 'text-amber-700' : 'text-burgundy-700'}`} role="timer" aria-live="off">
              {s.state === 'expired' ? 'Expired' : formatCountdown(s.secondsLeft)}
            </p>
            <div className="mt-2 h-2 overflow-hidden rounded-full bg-neutral-200" role="progressbar" aria-label="Token life left" aria-valuemin={0} aria-valuemax={100} aria-valuenow={Math.round(s.percentLeft)}>
              <div className={`h-full ${style.bar} transition-all`} style={{ width: `${s.percentLeft}%` }}/>
            </div>
          </div>
          <dl className="grid gap-x-6 gap-y-2 text-sm sm:grid-cols-2">
            <div><dt className="text-xs text-neutral-500">Generated</dt><dd>{fmtDateTime(s.token.issuedAt)}</dd></div>
            <div><dt className="text-xs text-neutral-500">Expires</dt><dd className={s.state === 'expired' ? 'font-semibold text-red-700' : ''}>{fmtDateTime(s.token.expiresAt)}</dd></div>
            <div><dt className="text-xs text-neutral-500">Shipex account</dt><dd>{s.token.email}</dd></div>
            <div><dt className="text-xs text-neutral-500">Generated by</dt><dd>{s.token.generatedBy ?? '—'}</dd></div>
            <div><dt className="text-xs text-neutral-500">Last successful pincode check</dt><dd>{fmtDateTime(s.token.lastCheckAt)}</dd></div>
          </dl>
          {s.token.expiredEarly && <p role="alert" className="rounded-lg bg-red-50 px-3 py-2 text-xs text-red-800">Shipex refused this token before its expiry time (it may have been replaced elsewhere). Generate a new one.</p>}
          {s.token.lastError && !s.token.expiredEarly && <p className="rounded-lg bg-amber-50 px-3 py-2 text-xs text-amber-900">Last problem: {s.token.lastError}</p>}
          <button type="button" className="rounded-lg border border-red-300 px-3 py-1 text-xs font-semibold text-red-700 hover:bg-red-50" onClick={onForget}>Remove saved token</button>
        </>)}
    </section>);
}
function GenerateForm({ onDone, hasToken }) {
    const [email, setEmail] = useState('');
    const [password, setPassword] = useState('');
    const [busy, setBusy] = useState(false);
    const [err, setErr] = useState('');
    const [ok, setOk] = useState('');
    const submit = async (e) => {
        e.preventDefault();
        if (busy)
            return;
        setBusy(true);
        setErr('');
        setOk('');
        try {
            await api('/admin/shipping/token', { body: { email: email.trim(), password } });
            setPassword(''); // the password is never kept in the page after use
            setOk('New token saved. It is valid for about 24 hours.'); notify.success('New token saved. It is valid for about 24 hours.');
            await onDone();
        }
        catch (x) {
            setErr(errText(x));
        }
        finally {
            setBusy(false);
        }
    };
    return (<form onSubmit={(e) => void submit(e)} className="card space-y-3" aria-labelledby="gen-h">
      <h2 id="gen-h" className="text-xl font-bold">{hasToken ? 'Generate a new token' : 'Generate token'}</h2>
      <p className="text-sm text-neutral-600">Enter your Shipex login. We exchange it for a token and save <b>only the token</b> (encrypted). Your password is not stored, so you will need to enter it again when the token expires.</p>
      <div className="grid gap-3 sm:grid-cols-2">
        <div><label htmlFor="sx-email" className="label">Shipex e-mail *</label><input id="sx-email" type="email" required autoComplete="off" className="input" value={email} onChange={(e) => setEmail(e.target.value)}/></div>
        <div><label htmlFor="sx-pass" className="label">Shipex password *</label><input id="sx-pass" type="password" required autoComplete="new-password" className="input" value={password} onChange={(e) => setPassword(e.target.value)}/></div>
      </div>
      {err && <p role="alert" className="rounded-lg bg-red-100 px-3 py-2 text-sm text-red-800">{err}</p>}
      {ok && <p role="status" className="rounded-lg bg-green-100 px-3 py-2 text-sm text-green-800">{ok}</p>}
      <button type="submit" className="btn-primary disabled:opacity-60" disabled={busy || !email || !password}>{busy ? 'Contacting Shipex…' : hasToken ? 'Generate new token' : 'Generate token'}</button>
    </form>);
}
function TestBox({ ready }) {
    const [f, setF] = useState({ pickUpPincode: '', deliveryPincode: '', paymentType: 'Prepaid' });
    const [res, setRes] = useState(null);
    const [busy, setBusy] = useState(false);
    const set = (k) => (e) => setF((x) => ({ ...x, [k]: e.target.value }));
    const run = async (e) => {
        e.preventDefault();
        setBusy(true);
        setRes(null);
        try {
            const r = await api('/admin/shipping/test', { body: f });
            setRes({ ok: true, serviceable: r.result.serviceable, message: r.result.message });
        }
        catch (x) {
            setRes({ ok: false, message: errText(x) });
        }
        finally {
            setBusy(false);
        }
    };
    return (<form onSubmit={(e) => void run(e)} className="card space-y-3" aria-labelledby="t-h">
      <h2 id="t-h" className="text-xl font-bold">Try a pincode</h2>
      <p className="text-sm text-neutral-600">Quick test with the saved token (default 0.5 kg, 10×10×10 cm, ₹500).</p>
      <div className="grid gap-3 sm:grid-cols-3">
        <div><label htmlFor="tp" className="label">Pickup pincode</label><input id="tp" inputMode="numeric" maxLength={6} className="input" value={f.pickUpPincode} onChange={set('pickUpPincode')}/></div>
        <div><label htmlFor="td" className="label">Delivery pincode</label><input id="td" inputMode="numeric" maxLength={6} className="input" value={f.deliveryPincode} onChange={set('deliveryPincode')}/></div>
        <div><label htmlFor="tt" className="label">Payment</label><select id="tt" className="input" value={f.paymentType} onChange={set('paymentType')}><option>Prepaid</option><option>COD</option></select></div>
      </div>
      <button type="submit" className="btn-ghost disabled:opacity-60" disabled={busy || !ready || !isPincode(f.pickUpPincode) || !isPincode(f.deliveryPincode)}>{busy ? 'Checking…' : 'Check'}</button>
      {!ready && <p className="text-xs text-neutral-500">Generate a valid token first.</p>}
      {res && <p role={res.ok ? 'status' : 'alert'} className={`rounded-lg px-3 py-2 text-sm ${!res.ok ? 'bg-red-100 text-red-800' : res.serviceable ? 'bg-green-100 text-green-800' : 'bg-amber-100 text-amber-900'}`}>
          {res.ok ? (res.serviceable ? '✓ Serviceable' : '✗ Not serviceable') : res.message}{res.ok && res.message ? ` — ${res.message}` : ''}</p>}
    </form>);
}
export default function Shipping() {
    const s = useShippingToken();
    const [msg, setMsg] = useState('');
    const forget = async () => {
        if (!window.confirm('Remove the saved courier token?\n\nPincode checks will stop until you generate a new one. Orders are not blocked.'))
            return;
        try {
            await api('/admin/shipping/token', { method: 'DELETE' });
            setMsg('Token removed.'); notify.remove('Token removed.');
            await s.refresh();
        }
        catch (e) {
            setMsg(errText(e));
        }
    };
    return (<>
      <PageHeader title="Shipping" subtitle="Courier connection (Shipex) used to check whether a pincode can be delivered to"/>
      {s.error && <p role="alert" className="mb-3 rounded-lg bg-red-100 px-3 py-2 text-sm text-red-800">{s.error}</p>}
      {msg && <p role="status" className="mb-3 rounded-lg bg-white px-3 py-2 text-sm text-burgundy-700 ring-1 ring-gold/40">{msg}</p>}
      <div className="grid max-w-3xl gap-4">
        <StatusCard s={s} onForget={() => void forget()}/>
        <GenerateForm hasToken={s.configured} onDone={s.refresh}/>
        <TestBox ready={s.configured && s.state !== 'expired'}/>
      </div>
    </>);
}
